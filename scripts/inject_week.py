def inject(html: str) -> str:
    names = ("孟子", "荀子", "彼得·德鲁克", "哈耶克", "俾斯麦")
    if all('n:"%s"' % n in html for n in names):
        print("week batch already in D")
        return html
    start = html.find("const D=[")
    if start < 0:
        raise SystemExit("const D=[ not found")
    i = html.index("[", start)
    depth = 0
    for j, ch in enumerate(html[i:], i):
        if ch == "[":
            depth += 1
        elif ch == "]":
            depth -= 1
            if depth == 0:
                end = j
                break
    else:
        raise SystemExit("D[] not closed")
    chunk = ",".join(
        block.strip() for block in BATCH.strip().rstrip(",]").split("},\n\n{")
    )
    # BATCH already a sequence of objects ending with }]
    add = BATCH.strip()
    if add.endswith("]"):
        add = add[:-1].rstrip()
    if add.startswith(","):
        add = add[1:]
    body = html[i + 1:end].rstrip()
    if not body.endswith(",") and not body.endswith("{") and body.strip():
        body = body + ","
    html = html[: i + 1] + body + add + html[end:]
    print("injected week batch")
    return html


