def convert(text):
    """简体 → 繁体（台湾）。已经是繁体的部分 OpenCC 会原样留下。"""
    if not text:
        return text
    out = _cc.convert(text)
    for a, b in FIX:
        out = out.replace(a, b)
    for a, b in POST:
        out = out.replace(a, b)
    return out


def load_allow():
    if not os.path.exists(ALLOW):
        return set()
    return {l.rstrip("\n") for l in open(ALLOW, encoding="utf-8") if l.strip() and not l.startswith("#")}


def contexts(text):
    """把转换后文本里每个歧义字取成三字上下文（前一字 + 本字 + 后一字）。

    为什么是三字而不是二字：分词错误恰好会造出**合法的二字词**——
    「明白髮生」里的「白髮」是个正经词，二字白名单放它过，就抓不到了。
    三字（白髮生）才认得出这是切错的。

    **左右邻字里的空白一律换成全角空格**（和文本两端的占位符同一个字符）。
    不是为了好看：`tw_allow.txt` 是**按行**存的，上下文里只要带一个换行，
    写进去时换行被当成行分隔符吃掉、读回来就少了一截，于是这一条
    **永远登记不上、每次都红**，而且人越登记越困惑（明明刚加过）。
    2026-09-17 把「里」纳进 AMBIGUOUS 时第一次撞上：瑪麗·居里的名字正好
    落在一行末尾，`居里\n` 这条卡了整整一轮。空白之间的区别对判据没有意义
    （换行和空格都表示「这里断开了」），归一成一个字符，格式就闭合了。
    """
    pad = lambda c: "　" if c.isspace() else c
    out = []
    n = len(text)
    for i, ch in enumerate(text):
        if ch in AMBIGUOUS:
            l = text[i - 1] if i > 0 else "　"
            r = text[i + 1] if i + 1 < n else "　"
            out.append(pad(l) + ch + pad(r))
    return out
