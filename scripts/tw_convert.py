#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""简体 → 繁体（台湾用字）转换的唯一入口。

为什么不是「跑一遍 OpenCC 就完了」——两条实测出来的坑：

一、**别用 s2twp**。它除了字形还替换词汇，在这个仓的语料上有硬伤：
      如循环之无端 → 如迴圈之無端   （孙子兵法原句，被当成编程的 loop）
      作者的对象   → 作者的物件
      支持的证据   → 支援的證據
      尚未通过     → 尚未透過
    我们的文本是历史与哲学散文，不是技术文档，所以只用 s2tw（字形 + 台湾异体），
    不动词汇。

二、**OpenCC 的分词会跨词边界切错**。它的分词词典只收「需要转换的词」，
    「明白」不在里面，于是「明白|发生」被贪心切成「明|白发|生」：
      明白发生了什么 → 明白髮生了什麼      ✗
      被发配到边疆   → 被髮配到邊疆        ✗
      还是只让我     → 還是隻讓我          ✗（副词「只」被当成量词「隻」）
    官方 C++ 版（opencc 1.4.2）也一样，这是原理性限制，不是包的 bug。
    所以下面有一张 FIX 表，逐条改回来 —— 表里每一条都是在真实语料里查证过的。

三、**新内容会带来新的歧义**。所以配套一道闸 `check_tw.py`：转换结果里每一个
    歧义字的三字上下文都必须在 `tw_allow.txt` 里登记过；出现没见过的就拦下来，
    要人看一眼再登记。写新章节时多出几条要审，这是有意的。
"""
import os
import re

import opencc

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
ALLOW = os.path.join(HERE, "tw_allow.txt")

_cc = opencc.OpenCC("s2tw")

# 一简多繁里，两个方向都讲得通、必须逐处确认的字。
# 只放**歧义**的：像 後/裡/於/發 这种绝大多数情况唯一解的不进来，否则闸会变成噪音。
AMBIGUOUS = "髮隻餘覆複麵乾鬆檯曆製彆繫捲穀僕醜範衝徵"

# ── 修正表：OpenCC 转错、必须改回的 ──────────────────────────────
# 每条后面注明依据。顺序有意义（先长后短），改动只发生在转换之后。
FIX = [
    # 「只」是副词，被当成量词「隻」。这些都是语料里逐条核对过的。
    ("還是隻", "還是只"), ("不是隻", "不是只"), ("多半隻", "多半只"),
    ("凡是隻", "凡是只"), ("都是隻", "都是只"), ("這是隻", "這是只"),
    ("大多隻", "大多只"), ("太多隻", "太多只"), ("別隻", "別只"),
    ("而隻字", "而只字"), ("富有隻", "富有只"), ("沒有隻是", "沒有只是"),
    ("那隻需要", "那只需要"), ("陽後隻立", "陽後只立"),
    # 「发」被当成「髮」（头发）。被髮左衽不动 —— 那里的「被髮」是披头散发，对的。
    ("明白髮生", "明白發生"), ("亂髮生", "亂發生"), ("被髮配", "被發配"),
    ("他髮長電", "他發長電"), ("生髮布", "生發布"), ("早髮型", "早發型"),
    ("墳墓被髮", "墳墓被發"),
    # 「面子」不是「麵」。「麵包」是对的，不动。
    ("和麵子", "和面子"),
    # 文言第一人称「余」（＝我），不是「其余」的「餘」。
    # 全语料 174 处「余」逐条分过：其余/剩余/业余/冗余/余地/余量/余裕/余额/余生/余气/
    # 余悉（其余全部）都该是「餘」，只有下面这几处是第一人称。
    ("餘甚惑焉", "余甚惑焉"),      # 《史记·伯夷列传》
    ("為餘謀", "為余謀"),          # 胡雪岩戒欺跋「谓诸君之善为余谋也可」
    ("餘存心濟世", "余存心濟世"),   # 同上「余存心济世，誓不以劣品弋取厚利」
    ("心餘之心", "心余之心"),      # 同上「叮嘱各位管事心余之心」
    # 人名：范祖禹（《资治通鉴》分修者），姓「范」。
    ("範祖禹", "范祖禹"),
    # 「年历史」被切成「年历|史」。
    ("年曆史", "年歷史"),
]

# 繁体里**绝不该出现**的组合。它们只可能来自分词切错 ——
# 这一条是系统性的：逐字审只能看见你想到要看的字，这张表一次能把
# 「核心系统→核心繫統」「强调制度→強調製度」这类扫出来（播客站就是这么抓到的）。
# 只放高置信度的：「隻看」「隻用」这种量词后接动词是合法的
# （「一隻用統計學思考的火雞」），放进来会变成噪音。
NEVER = (
    "繫統 髮生 髮明 髮現 髮展 髮布 髮起 髮動 髮配 髮送 髮表 髮言 髮揮 髮達 髮電 髮射 髮行 "
    "隻能 隻有 隻是 隻要 隻好 隻剩 "
    "麵對 麵臨 麵子 麵前 麵積 麵板 麵貌 麵向 麵試 "
    "乾部 乾預 乾擾 乾涉 曆史 曆程 曆來 徵服 徵途 徵戰 "
    "製度 體製 機製 控製 專製 限製 抑製 強製 調製度 "
    "鬆樹 穀歌 試捲 問捲 僕後 檯風 覆雜 覆習 姓範 彆的 彆人 醜時"
).split()


# 用字风格统一（不是纠错，是选一种写法并贯彻）
POST = [
    # 台湾教育部把「佈」并入「布」，标准写法是宣布 / 发布 / 分布 / 布置 / 布局。
    # OpenCC 各档都给「佈」（偏港式），这里统一改回台湾标准。
    # 整字替换是安全的：「佈」在教育部字表里就是「布」的异体，没有只能用「佈」的词。
    ("佈", "布"),
]


def convert(text):
    """简体 → 繁体（台湾）。已经是繁体的部分 OpenCC 会原样留下。"""
    if not text:
        return text
    out = _cc.convert(text)
    for a, b in FIX:
        out = out.replace(a, b)
    for a, b in POST:
        out = out.replace(a, b)
    return out


def load_allow():
    if not os.path.exists(ALLOW):
        return set()
    return {l.rstrip("\n") for l in open(ALLOW, encoding="utf-8") if l.strip() and not l.startswith("#")}


def contexts(text):
    """把转换后文本里每个歧义字取成三字上下文（前一字 + 本字 + 后一字）。

    为什么是三字而不是二字：分词错误恰好会造出**合法的二字词**——
    「明白髮生」里的「白髮」是个正经词，二字白名单放它过，就抓不到了。
    三字（白髮生）才认得出这是切错的。
    """
    out = []
    n = len(text)
    for i, ch in enumerate(text):
        if ch in AMBIGUOUS:
            l = text[i - 1] if i > 0 else "　"
            r = text[i + 1] if i + 1 < n else "　"
            out.append(l + ch + r)
    return out
